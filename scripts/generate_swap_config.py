#!/usr/bin/env python3
"""Generate llama-swap config.yml + isolated-tier cmd files from the manifest.

Stdlib only. The manifest (models/models.toml) is the source of truth;
this script never invents values and fails closed naming the offending
entry when the manifest violates the contract (pin fields present, cmd
references the local dest, isolated/port and ${PORT} rules respected).

Outputs into --out-dir:
  config.yml           - llama-swap config: A1 apiKeys as env macros,
                         globalTTL, one entry per non-isolated model
  isolated-<name>.cmd  - one line per isolated entry, ${PORT} replaced
                         by the entry's fixed port
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

API_KEYS = [
    "${env.LLAMA_SWAP_KEY_OPERATOR}",
    "${env.LLAMA_SWAP_KEY_FAMILY}",
    "${env.LLAMA_SWAP_KEY_AGENTS}",
]
GLOBAL_TTL = 1800
REQUIRED_PINS = ("repo", "rev", "file", "dest", "sha256")


def fail(entry: str, problem: str) -> "SystemExit":
    print(f"generator FAIL: entry {entry!r}: {problem}", file=sys.stderr)
    sys.exit(1)


def yaml_quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def validate(entries: list[dict]) -> None:
    for e in entries:
        name = e.get("name", "<unnamed>")
        for field in REQUIRED_PINS:
            if not e.get(field):
                fail(name, f"missing pin field {field!r}")
        swap = e.get("swap", {}).get("cmd", "")
        if not swap:
            fail(name, "missing swap.cmd")
        if e["dest"] not in swap:
            fail(name, f"swap.cmd does not reference its dest {e['dest']!r}")
        if e.get("isolated"):
            if not isinstance(e.get("port"), int):
                fail(name, "isolated entry lacks an integer port")
        elif "${PORT}" not in swap:
            fail(name, "non-isolated entry lacks ${PORT} in swap.cmd")
        first = swap.split(" ", 1)[0]
        if first != "llama-server":
            fail(name, f"first cmd token must be llama-server, got {first!r}")
        m = re.search(r"-m\s+(\S+)", swap)
        if not m:
            fail(name, "cmd lacks -m <model path>")
        if m.group(1).startswith("/"):
            fail(
                name,
                f"-m value must be RELATIVE (got {m.group(1)!r}); "
                "the generator prepends --models-root",
            )


def rewrite(cmd: str, llama_server: str, models_root: str, entry: str) -> str:
    """Replace the placeholder first token and single-prefix the -m path."""
    _, rest = cmd.split(" ", 1)
    val = re.search(r"-m\s+(\S+)", cmd).group(1)
    rest = rest.replace("-m " + val, f"-m {models_root}/{val}", 1)
    return llama_server + " " + rest


def emit(entries: list[dict], llama_server: str, models_root: str, out_dir: Path) -> None:
    lines = [
        "# GENERATED by scripts/generate_swap_config.py - do not edit by hand.",
        "# Source of truth: models/models.toml. Regenerate via nix/inference.nix.",
        "apiKeys:",
    ]
    lines += [f"  - {yaml_quote(k)}" for k in API_KEYS]
    lines += [f"globalTTL: {GLOBAL_TTL}", "models:"]

    matrix = [e for e in entries if not e.get("isolated")]
    if not matrix:
        fail("<manifest>", "no non-isolated entries - the swap matrix would be empty")

    for e in matrix:
        cmd = rewrite(e["swap"]["cmd"], llama_server, models_root, e["name"])
        lines += [
            f"  {yaml_quote(e['name'])}:",
            "    cmd: |",
            *(f"      {ln}" for ln in cmd.splitlines()),
            "",
        ]

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "config.yml").write_text("\n".join(lines) + "\n")

    for e in (x for x in entries if x.get("isolated")):
        cmd = e["swap"]["cmd"].replace("${PORT}", str(e["port"]))
        cmd = rewrite(cmd, llama_server, models_root, e["name"])
        (out_dir / f"isolated-{e['name']}.cmd").write_text(cmd + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest", type=Path, required=True)
    ap.add_argument(
        "--llama-server", required=True, help="absolute path to the llama-server binary"
    )
    ap.add_argument(
        "--models-root", required=True, help="absolute root under which model files live"
    )
    ap.add_argument("--out-dir", type=Path, required=True)
    args = ap.parse_args()

    if not args.llama_server.startswith("/"):
        fail("<cli>", "--llama-server must be an absolute path")
    if not args.models_root.startswith("/"):
        fail("<cli>", "--models-root must be an absolute path")

    entries = tomllib.loads(args.manifest.read_text()).get("models", [])
    if not entries:
        fail("<manifest>", "no [[models]] entries")
    validate(entries)
    emit(entries, args.llama_server, args.models_root, args.out_dir)
    matrix = sum(1 for e in entries if not e.get("isolated"))
    isolated = len(entries) - matrix
    print(
        f"generator: wrote config.yml ({matrix} matrix) "
        f"+ {isolated} isolated cmd(s) to {args.out_dir}"
    )


if __name__ == "__main__":
    main()
